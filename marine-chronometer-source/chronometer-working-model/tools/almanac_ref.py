"""Reference data for checking the nautical almanac (js, from Meeus's Astronomical Algorithms): Sun, Moon, the navigational stars, sidereal time.
Writes almanac-ref.json beside this script; the almanac's figures are compared with it, it is not regenerated by the build.

    python almanac_ref.py [--py DIR] [--eph DIR] [--out FILE]     # needs the network; a few minutes

Fetched (raw HTTP):
  - SIMBAD's TAP service (https://simbad.cds.unistra.fr/simbad/sim-tap/sync, ADQL over basic, ident, allfluxes, flux): for the Nautical Almanac's 57
    selected stars and Polaris, ICRS J2000 ra, dec (deg), pmra (mas/yr, with cos dec), pmdec, parallax (mas), radial velocity (km/s), V and the HIP
    number. A field SIMBAD leaves empty on the id asked for is taken from the entry in FILL (the system or the component) and named in "fill".
  - JPL Horizons' API (https://ssd.jpl.nasa.gov/api/horizons.api), observer tables (Venus 299 and Mars 499 too, quantity 2 and 20, at the epochs before 2050), TIME_TYPE UT, APPARENT AIRLESS, ANG_FORMAT DEG, EXTRA_PREC YES:
    geocentric (500@399) Sun (10) and Moon (301) quantity 2 (apparent RA/Dec: for Earth-based sites "with respect to the true-equator and Earth equinox
    of-date coordinate system (EOP-corrected IAU76/80 precession and nutation ...) and adjusted to model light-time, the gravitational deflection of
    light, and stellar aberration", Horizons manual), 20 (range: the Sun in au, the Moon in km), 23 (the Moon's S-O-T elongation), 30 (TDB-UT) and 49
    (UT1-UTC); topocentric (coord@399, GEODETIC) quantity 4 (apparent azimuth, elevation) at three sites.
Computed with skyfield (pip install --target DIR skyfield; --py DIR or ALMANAC_PY puts DIR on sys.path) and JPL's de440s.bsp (1849-2150, downloaded
into --eph DIR or ALMANAC_EPH, default ~/skyfield-data): the stars' geocentric apparent places of date (earth.at(t).observe(star).apparent()
.radec(epoch='date'), proper motion, parallax and radial velocity included) and GMST, GAST at each epoch, at UT1 = UTC + Horizons' UT1-UTC.

Times: "utc" is the time asked for (Horizons' UT: UT1 before 1962, UTC after); jd_ut is its JD. dT is TT - UT from Horizons' TDB-UT (less skyfield's
TDB - TT from 1962, when Horizons keeps the distinction); dut1 is UT1 - UTC (0 before 1962). Beyond its EOP predictions (about 78 days) Horizons holds
TT - UTC and UT1 - UTC constant, so its dT after 2026 stays near 69.2 s: an almanac checked against these Moon places must use this dT, not its own.
Epochs: 60 drawn from 1950-2149 and 30 from 2026-2035 by random.Random(SEED), whole minutes."""
