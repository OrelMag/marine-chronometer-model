def get(url,data=None,tries=5):
    for k in range(tries):
        try:
            with urllib.request.urlopen(url,data,timeout=180) as f: return json.load(f)
        except Exception as e:
            if k==tries-1: raise
            print('  retry',k+1,e);time.sleep(5*(k+1))
def tap(q):
    r=get('https://simbad.cds.unistra.fr/simbad/sim-tap/sync',urllib.parse.urlencode({'request':'doQuery','lang':'adql','format':'json','query':q}).encode())
    c=[m['name'] for m in r['metadata']];return [dict(zip(c,row)) for row in r['data']]
def simbad(ids):   # one row per id asked for: astrometry, V (allfluxes, else flux V), the HIP number
    L="','".join(ids);rows=tap(f"""SELECT i.id AS q,b.main_id,b.ra,b.dec,b.pmra,b.pmdec,b.plx_value,b.rvz_radvel,a.V AS va,f.flux AS vf,h.id AS hip
 FROM basic AS b JOIN ident AS i ON i.oidref=b.oid LEFT JOIN allfluxes AS a ON a.oidref=b.oid LEFT JOIN flux AS f ON f.oidref=b.oid AND f.filter='V'
 LEFT JOIN ident AS h ON h.oidref=b.oid AND h.id LIKE 'HIP %' WHERE i.id IN ('{L}')""")
    n=lambda s:' '.join(s.replace('*','').split());out={}
    for r in rows:
        out[n(r['q'])]=dict(main=n(r['main_id']),ra=r['ra'],dec=r['dec'],pmra=r['pmra'],pmdec=r['pmdec'],plx=r['plx_value'],rv=r['rvz_radvel'],
          v=r['va'] if r['va'] is not None else r['vf'],hip=int(r['hip'].split()[1]) if r['hip'] else None)
    miss=[i for i in ids if n(i) not in out];assert not miss,f'SIMBAD has no {miss}';return {i:out[n(i)] for i in ids}
def stars():
    S=simbad([s[2] for s in STARS]+list(FILL.values()));res=[]
    for n,name,i in STARS:
        r=dict(S[i]);fill={}
        for k,v in r.items():
            if v is None and i in FILL and S[FILL[i]][k] is not None: r[k]=S[FILL[i]][k];fill[k]=FILL[i]
        e=dict(n=n,name=name,id=i,hip=r['hip'],ra=R(r['ra'],9),dec=R(r['dec'],9),pmra=r['pmra'],pmdec=r['pmdec'],plx=r['plx'],rv=r['rv'],v=r['v'])
        if fill: e['fill']=fill
        if r['v'] is None or r['v']>3.1 or None in (r['hip'],r['plx'],r['rv'],r['pmra']): print(f'  check {n} {name} ({i}): V {r["v"]}, HIP {r["hip"]}, plx {r["plx"]}, rv {r["rv"]}')
        res.append(e)
    return res
HZ='https://ssd.jpl.nasa.gov/api/horizons.api';SRC={}
def horizons(cmd,tl,center="'500@399'",q='2,20,30,49',extra={},N=20):   # rows of the CSV table, one per epoch of tl (calendar strings, UT), N epochs a request (a long TLIST gets a 502)
    if len(tl)>N: return [r for k in range(0,len(tl),N) for r in horizons(cmd,tl[k:k+N],center,q,extra,N)]
    p=dict(format='json',COMMAND=f"'{cmd}'",OBJ_DATA="'NO'",MAKE_EPHEM="'YES'",EPHEM_TYPE="'OBSERVER'",CENTER=center,TLIST=' '.join(f"'{t}'" for t in tl),
      TLIST_TYPE="'CAL'",TIME_TYPE="'UT'",QUANTITIES=f"'{q}'",ANG_FORMAT="'DEG'",EXTRA_PREC="'YES'",APPARENT="'AIRLESS'",CSV_FORMAT="'YES'",**extra)
    r=get(HZ+'?'+urllib.parse.urlencode(p));time.sleep(1.5);t=r['result']
    if '$$SOE' not in t: raise SystemExit('Horizons: '+t[-2000:])
    for ln in t.splitlines():
        if '{source:' in ln and 'Target body' in ln: SRC['eph']=ln.split('{source:')[1].strip(' }')
        if ln.startswith('EOP file'): SRC['eop']=ln.split(':',1)[1].strip()
    hd=t[:t.index('$$SOE')].splitlines()[-2];cols=[c.strip() for c in hd.split(',')]
    rows=[dict(zip(cols,[c.strip() for c in ln.split(',')])) for ln in t[t.index('$$SOE')+5:t.index('$$EOE')].strip().splitlines()]
    assert len(rows)==len(tl),(len(rows),len(tl));return rows
f=lambda s:None if s in ('n.a.','') else float(s)
def epochs():
    g=random.Random(SEED);a=dt.datetime(1950,1,1);mins=lambda d0,d1:g.randrange(int((d1-d0).total_seconds()//60))
    E=sorted(a+dt.timedelta(minutes=mins(a,dt.datetime(2150,1,1))) for _ in range(60))
    b=dt.datetime(2026,1,1);E+=sorted(b+dt.timedelta(minutes=mins(b,dt.datetime(2036,1,1))) for _ in range(30));return E
iso=lambda d:d.strftime('%Y-%m-%dT%H:%M');cal=lambda d:d.strftime('%Y-%m-%d %H:%M')
def jd(d): return (d-dt.datetime(2000,1,1,12)).total_seconds()/86400+2451545.0
def main():
    ld=Loader(EPH,verbose=False);ts=ld.timescale();eph=ld('de440s.bsp');earth=eph['earth']
    print('SIMBAD ...');st=stars()
    print('stars apparent ...');sa=[]
    for u in APP:
        d=dt.datetime.fromisoformat(u);t=ts.utc(d.year,d.month,d.day,d.hour,d.minute);ra,dec=[],[]
        for s in st:
            S=Star(ra_hours=s['ra']/15,dec_degrees=s['dec'],ra_mas_per_year=s['pmra'] or 0,dec_mas_per_year=s['pmdec'] or 0,parallax_mas=s['plx'] or 0,radial_km_per_s=s['rv'] or 0)
            a,de,_=earth.at(t).observe(S).apparent().radec(epoch='date');ra.append(R(a._degrees,7));dec.append(R(de.degrees,7))
