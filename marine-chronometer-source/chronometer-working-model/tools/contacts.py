"""The Contacts view (../../shared/contacts.js) rendered and listed: every pair of parts that touch, come close or pass into each other, as the page's own Contacts finds them.

    python contacts.py --model wempe                   # this moment: r_ct_movement.png, r_ct_escapement.png, r_ct_side.png, r_ct_exploded.png and r_ct_pairs.json here; the pairs printed
    python contacts.py --model wempe --sweep           # over a beat and the wind (the states fine.py checks), each pair with the states it meets in
    python contacts.py --model wempe --part fusee      # that part's contacts alone (the page's pick), its pairs listed; --inside adds its own pieces' contacts
    python contacts.py --model wempe --hide topPlate,pillarPlate   # those parts hidden, their contacts with them; --views plan,side the views rendered
    python contacts.py --model wempe --eps 0.1         # the band counted close (0.01, 0.03, 0.1, 0.3 or 1 mm; 0.03 by default)
    python contacts.py --model wempe --eval JS         # run code after loading (a version: "__mv.userData.setRev('first')")
    python contacts.py --model wempe --write           # js/contactdata.js (WCONTACT) from checks.py's EXPECTED and STATES: what the page calls expected, and the sweep's states
    python contacts.py --model wempe --check           # exit 1 if js/contactdata.js is stale (no browser)

It reports and never fails on what it finds (fine.py is the check that fails on an overlap); exit 1 only on a page error or a stale contactdata.js. The Hamilton's page has no
Contacts view yet. Kinds: touching (the solids within 0.006 mm either way), close (a gap up to the band), overlap expected (a pair fine.py's EXPECTED lists, with its reason),
overlap not expected."""
import asyncio,json,pathlib,sys,time
import model,browser
sys.stdout.reconfigure(encoding='utf-8')
HERE=pathlib.Path(__file__).resolve().parent
def arg(k,d=None):
    if k in sys.argv:i=sys.argv.index(k);return sys.argv[i+1]
    return d
DATA=model.cfg('CONTACTDATA')   # (path beside index.html, the global it declares)
def data_js():
    exp={'|'.join(sorted(k)):v[0] for k,v in model.cfg('EXPECTED',{}).items()}
    st=[[ph,dE,n,bool(w)] for ph,dE,n,w in model.cfg('STATES',[])]
    return (f"/* Generated by tools/contacts.py --model {model.NAME} --write from checks.py: what the Contacts view (../../shared/contacts.js) counts as an expected overlap (fine.py's EXPECTED,\n"
            f"   'part:Type|part:Type': why) and the states its sweep poses the model in (fine.py's STATES: balance phase, escape teeth on, fusee turns from full wind, winding). Don't edit. */\n"
            f"const {DATA[1]}={{expected:{json.dumps(exp,ensure_ascii=False)},\nstates:{json.dumps(st)}}};\n")
async def main():
    if not DATA:print(f'{model.NAME}: its page has no Contacts view yet');sys.exit(2)
    f=model.DIR/DATA[0]
    if '--write' in sys.argv:f.write_text(data_js(),encoding='utf-8',newline='\n');print('wrote',f);return
    ok=f.exists() and f.read_text(encoding='utf-8')==data_js();errs=[] if ok else [f'{f.name} is stale: run contacts.py --model {model.NAME} --write']
    if '--check' in sys.argv:print(f'{f.name}: '+('up to date' if ok else 'stale'));sys.exit(0 if ok else 1)
    views=(arg('--views') or 'movement,escapement,side,exploded').split(',')
    h='contacts='+('sweep' if '--sweep' in sys.argv else '1')+('&ctin=1' if '--inside' in sys.argv else '')+(f"&ceps={arg('--eps')}" if arg('--eps') else '')+'&merge=0'
    from playwright.async_api import async_playwright
    async with async_playwright() as p:
        b=await p.chromium.launch(args=browser.ARGS);pg=await b.new_page(viewport={"width":1500,"height":1000})
        pg.on("pageerror",lambda e:errs.append(str(e)));pg.on("console",lambda m:m.type=='error' and errs.append(m.text))
        await pg.goto(model.PAGE);await pg.wait_for_function("!document.querySelector('#loading')",timeout=120000);await pg.wait_for_timeout(1500)
        if arg('--eval'):await pg.evaluate(arg('--eval'))
        for k in (arg('--hide') or '').split(','):
            if k:await pg.evaluate("k=>{const r=[...document.querySelectorAll('#plist .prow')].find(r=>r.querySelector('.pn').textContent===window.__parts[k]?.t);if(!r)throw Error('no part '+k);r.firstChild.click();}",k)
        t=time.time();await pg.evaluate(f"location.hash='{h}'");await pg.wait_for_timeout(500)
        await pg.wait_for_function("window.__ct&&__ct.on()&&!__ct.busy()",timeout=1800000,polling=500)
        if arg('--part'):
            await pg.evaluate(f"location.hash=location.hash+'&part={arg('--part')}'");await pg.wait_for_timeout(500);await pg.wait_for_function("!__ct.busy()",timeout=600000,polling=300)
        print(f"found in {time.time()-t:.1f} s")
        await pg.evaluate("document.documentElement.classList.add('nopanel')");await pg.wait_for_timeout(300)
        pairs=await pg.evaluate("__ct.pairs()");labels=await pg.evaluate("__ct.labels()");n=await pg.evaluate("__ct.counts()")
        for v in views:
            await pg.evaluate(f"document.querySelector('#views button[data-v=\"{v}\"]').click()");await pg.wait_for_timeout(1500)
            if arg('--part'):await pg.evaluate(f"location.hash=location.hash+'&part={arg('--part')}'");await pg.wait_for_timeout(400);await pg.wait_for_function("!__ct.busy()",timeout=600000,polling=300);await pg.wait_for_timeout(500)   # a view's button closes the card, and the pick with it
            await pg.locator('#stage').screenshot(path=f'r_ct_{v}.png');print('wrote',f'r_ct_{v}.png')
        await b.close()
    pathlib.Path('r_ct_pairs.json').write_text(json.dumps({'labels':labels,'pairs':pairs},indent=1,ensure_ascii=False),encoding='utf-8')
    print(f"{len(pairs)} pairs: {n[0]} touching, {n[1]} close, {n[2]} overlapping as expected, {n[3]} overlapping not expected (a pair counts under each kind it shows)"+(f", over {len(labels)} states" if labels else ''))
    O=['overlap, not expected','overlap, expected','touching','close']
    for q in sorted(pairs,key=lambda q:(O.index(q['kind']),-q['depth'],q['gap'] or 0)):
        k=q['kind'];d=f"overlap {q['depth']:.3f} mm" if k.startswith('overlap') else '' if k=='touching' else f"gap {q['gap']:.3f} mm"
        ns=len(set(sum(q['states'],[])));w=f"  in {ns} of {len(labels)} states" if labels else ''
        print(f"  {'!! ' if k=='overlap, not expected' else '   '}{k:22s} {q['an']+' – '+q['bn']:75s} {d}{w}{'  (inside)' if q['inside'] else ''}")
    for e in errs:print('ERROR',e)
    sys.exit(1 if errs else 0)
asyncio.run(main())
